"""Builds the Worker's two data modules from the demo bundle and the project docs.

  src/catalog.js    every title the demo can recommend, so the Worker only returns real catalog entries
  src/knowledge.js  README, DECISIONS and about.md, which the assistant answers project questions from

Run from the repo root after the bundle changes:  python deploy/ask-worker/scripts/build_data.py
"""
from __future__ import annotations

import html
import json
import re
from pathlib import Path

import numpy as np
import polars as pl

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "artifacts" / "demo"
COVER_PREFIX = "https://cdn.myanimelist.net/images/anime/"


def catalog() -> list[list]:
    items = pl.read_parquet(BUNDLE / "items.parquet")
    arrays = np.load(BUNDLE / "arrays.npz")
    popularity = (arrays["item_counts_cf"] + arrays["recent_counts"]).tolist()
    rows = []
    for i, r in enumerate(items.iter_rows(named=True)):
        # The display title is what the app's search box and saved preferences use, so it must stay exact.
        name = html.unescape(r["display_title"])
        romaji = html.unescape(r["title"]) if r["title"] and r["title"] != r["display_title"] else ""
        cover = r["cover_url"] or ""
        cover = cover[len(COVER_PREFIX):] if cover.startswith(COVER_PREFIX) else ""
        score = r["display_score"]
        rows.append([
            name, romaji, r["year"] or 0, r["type"] or "", r["anime_id"], cover,
            int(round(score * 10)) if score is not None and score == score else 0, int(popularity[i]),
        ])
    return rows


def knowledge() -> str:
    readme = (ROOT / "README.md").read_text()
    readme = re.sub(r"```mermaid.*?```", "", readme, flags=re.S)
    readme = re.sub(r"<!--.*?-->", "", readme)
    readme = re.split(r"\n## Setup and commands", readme)[0]
    decisions = (ROOT / "DECISIONS.md").read_text()
    about = (HERE / "about.md").read_text()
    return "\n\n".join(s.strip() for s in [about, readme, decisions])


def main() -> None:
    rows = catalog()
    (HERE / "src" / "catalog.js").write_text(
        "// Generated by scripts/build_data.py from artifacts/demo. Do not edit.\n"
        "// [title, romaji title or '', year, type, MyAnimeList id, cover path, score x10, popularity]\n"
        f"export default {json.dumps(rows, ensure_ascii=False, separators=(',', ':'))};\n"
    )
    text = knowledge()
    (HERE / "src" / "knowledge.js").write_text(
        "// Generated by scripts/build_data.py from README.md, DECISIONS.md and about.md. Do not edit.\n"
        f"export default {json.dumps(text, ensure_ascii=False)};\n"
    )
    print(f"catalog: {len(rows)} titles; knowledge: {len(text)} characters")


if __name__ == "__main__":
    main()
